-- Cube Academy — migrazione 5: eventi gestiti dal pannello (pagina #/eventi del sito).
-- Esegui nel SQL Editor di Supabase dopo migrazione-4.sql. È idempotente.
--
-- Ogni evento è un "articolo": titolo, immagine, descrizione nelle 4 lingue, link all'evento,
-- date di inizio e fine (coincidenti se dura una sola giornata). Niente commenti.

create table if not exists public.eventi (
  id             bigint generated by default as identity primary key,
  titolo         text    not null,
  pubblicato     boolean not null default true,
  data_inizio    date,                       -- vuoto = "data da definire"
  data_fine      date,                       -- uguale a data_inizio se l'evento dura un giorno
  luogo          text,
  link_evento    text,                       -- sito o pagina ufficiale dell'evento
  immagine_url   text,
  descrizione_it text,
  descrizione_en text,
  descrizione_fr text,
  descrizione_de text,
  created_at     timestamptz not null default now()
);

alter table public.eventi enable row level security;

-- il sito (anon) legge solo gli eventi pubblicati; gli admin gestiscono tutto
drop policy if exists eventi_public_read on public.eventi;
create policy eventi_public_read on public.eventi
  for select to anon, authenticated using (pubblicato);

drop policy if exists eventi_admin_all on public.eventi;
create policy eventi_admin_all on public.eventi
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Archivio delle immagini degli eventi (lettura pubblica, scrittura solo admin)
insert into storage.buckets (id, name, public)
values ('eventi', 'eventi', true)
on conflict (id) do nothing;

drop policy if exists eventi_img_public_read on storage.objects;
create policy eventi_img_public_read on storage.objects
  for select using (bucket_id = 'eventi');

drop policy if exists eventi_img_admin_insert on storage.objects;
create policy eventi_img_admin_insert on storage.objects
  for insert to authenticated with check (bucket_id = 'eventi' and public.is_admin());

drop policy if exists eventi_img_admin_update on storage.objects;
create policy eventi_img_admin_update on storage.objects
  for update to authenticated using (bucket_id = 'eventi' and public.is_admin());

drop policy if exists eventi_img_admin_delete on storage.objects;
create policy eventi_img_admin_delete on storage.objects
  for delete to authenticated using (bucket_id = 'eventi' and public.is_admin());

